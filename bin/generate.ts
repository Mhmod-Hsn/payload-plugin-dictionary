#!/usr/bin/env node

/**
 * CLI: `npx payload-dictionary generate`
 *
 * Connects to the local Payload database, fetches every translation key
 * across all namespaces, and writes a `dictionary.d.ts` file to the
 * project root containing a `TranslationKeys` union type.
 *
 * Usage:
 *   npx payload-dictionary generate
 *   npx payload-dictionary generate --out ./types/dictionary.d.ts
 */

import fs from 'node:fs'
import path from 'node:path'
import { getPayload } from 'payload'

async function main(): Promise<void> {
  const args = process.argv.slice(2)

  if (args[0] !== 'generate') {
    console.error('Usage: payload-dictionary generate [--out <path>]')
    process.exit(1)
  }

  // Resolve the output path from --out flag or default to project root.
  let outFile = path.resolve(process.cwd(), 'dictionary.d.ts')
  const outIndex = args.indexOf('--out')
  if (outIndex !== -1 && args[outIndex + 1]) {
    outFile = path.resolve(process.cwd(), args[outIndex + 1])
  }

  console.log('🔗 Connecting to Payload...')

  // Dynamically import the user's Payload config.
  // The PAYLOAD_CONFIG_PATH env variable must point to the config file.
  const configPath = process.env.PAYLOAD_CONFIG_PATH
  if (!configPath) {
    console.error(
      '❌ PAYLOAD_CONFIG_PATH is not set. Please set it to your payload.config.ts path.',
    )
    process.exit(1)
  }

  const importedConfig = await import(path.resolve(process.cwd(), configPath))
  const config = importedConfig.default || importedConfig

  const payload = await getPayload({ config })

  console.log('📖 Fetching translation keys...')

  const { docs } = await payload.find({
    collection: 'translations',
    pagination: false,
    depth: 0,
  })

  if (docs.length === 0) {
    console.warn('⚠️  No translations found. Writing empty type definition.')
  }

  // Build sorted union members: "namespace:key"
  const keys = docs
    .map((doc) => {
      const ns = doc.namespace as string
      const key = doc.key as string
      return `${ns}:${key}`
    })
    .sort()

  // Deduplicate (shouldn't happen, but defensive)
  const uniqueKeys = [...new Set(keys)]

  // Generate the .d.ts content.
  const unionMembers = uniqueKeys.map((k) => `  | "${k}"`).join('\n')

  const content = `// ──────────────────────────────────────────────────────────────
// This file is auto-generated by payload-dictionary-plugin.
// Do not edit manually. Re-run: npx payload-dictionary generate
// ──────────────────────────────────────────────────────────────

export type TranslationKeys =
${unionMembers || '  never'}
`

  // Ensure the output directory exists.
  const outDir = path.dirname(outFile)
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true })
  }

  fs.writeFileSync(outFile, content, 'utf-8')
  console.log(`✅ Generated ${path.relative(process.cwd(), outFile)} with ${uniqueKeys.length} key(s).`)

  process.exit(0)
}

main().catch((err) => {
  console.error('❌ Failed to generate dictionary types:', err)
  process.exit(1)
})
